def build_script_sheet(wb, cfg):
    rows = SCRIPTS[cfg["key"]]
    ws = wb.create_sheet("설명 스크립트(슈퍼바이저용)", 0)
    hide_gridlines(ws)
    colw(ws, {"A": 6, "B": 7, "C": 24, "D": 84, "E": 42, "F": 36})
    title(ws, f'설명 스크립트 — {cfg["teacher"]} 선생님 슈퍼비전 (내부용 · 슈퍼바이지에게 배포하지 않음)', 6)
    merged(ws, 2, 1, 6, "이 시트는 설명용 사본입니다. 예시(가상) 자료가 채워져 있어 기초선 → 중재 → 유지가 표·그래프로 어떻게 보이는지 바로 보여 줄 수 있습니다. "
           "배포용 최종본에는 예시 자료와 이 탭이 없습니다. 말씀 그대로 읽어도 되고, 요지만 풀어 말씀하셔도 됩니다.", color=BLUE, bold=True)
    for i, h in enumerate(["순서", "분", "화면(탭)", "말할 내용", "보여 줄 것", "확인·주의"]):
        put(ws, f"{CL(1+i)}3", h, bold=True, bg=SECT, h="center", border=True)
    r = 3
    tot = 0
    for no, mins, tab, say, show, note in rows:
        r += 1
        tot += mins
        put(ws, f"A{r}", no, h="center", border=True)
        put(ws, f"B{r}", mins, h="center", border=True)
        put(ws, f"C{r}", tab, bold=True, border=True)
        put(ws, f"D{r}", say, border=True)
        put(ws, f"E{r}", show, border=True, size=9)
        put(ws, f"F{r}", note, border=True, size=9)
        h = max(lines_needed(say, 84), lines_needed(show, 42) * 0.9, lines_needed(note, 36) * 0.9) * 13.8 + 8
        ws.row_dimensions[r].height = h
    r += 1
    put(ws, f"A{r}", "합계", bold=True, h="center", border=True, bg=LABEL)
    put(ws, f"B{r}", tot, bold=True, h="center", border=True, bg=LABEL)
    merged(ws, r, 3, 6, "약 " + str(tot) + "분 (질문 시간 포함해 여유 있게 잡으세요)", size=9, color=GRAY_TXT)
    ws.freeze_panes = "A4"
    return ws
